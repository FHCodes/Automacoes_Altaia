import os
import re
import copy
import importlib

# Local libraries
BaseOperator = importlib.import_module("shelf.collectorprocess.operators.BaseOperator").BaseOperator
FamilyObject = importlib.import_module("shelf.collectorprocess.operators.FamilyObject").FamilyObject
BaseCommand = importlib.import_module("shelf.collectorprocess.operators.Readers.ALCATEL.COMMANDS.Operator").Command
logger = importlib.import_module("shelf.collectorprocess.logger").logger


# Command class that extends the base command defined in Operator.py
class Command(BaseCommand):

    def __init__(self):
        self._file_name_regex = re.compile(r'^RMFS.*$')
        self._command_name = 'GPRS'
        self._lineSepRegex = re.compile(r'\t')

    @property
    def line_format(self):
        return self._line_format

    def parse(self, file_path):
        logger.debug("Parsing GPRS format, in file {0}".format(os.path.basename(file_path)))

        file_name = os.path.basename(file_path)

        # Open file for reading
        try:
            command_name_list = ['BEARERCHANNEL', 'PVC', 'LAPD', 'CELL', 'DISTCELL', 'BTS', 'BSC']
            f = open(file_path)
            lines = f.readlines()
            f.close()

            header_data = dict()
            while len(lines) > 0:
                line = lines.pop(0).strip('\n|\r')
                if line == '':
                    break

                # Read file header
                if line.startswith('MFS version'):
                    header_data['MFS_RELEASE'] = line.split(': ')[1].strip() + '.'
                elif line.startswith('MFS subversion'):
                    header_data['MFS_RELEASE'] += line.split(': ')[1].strip()
                elif line.startswith('Number of the MFS'):
                    header_data['MFS_NAME'] = line.split(': ')[1].strip()
                elif line.startswith('Measurement begin date and time'):
                    header_data['RESULT_TIME_START'] = line.split(': ')[1].strip() + ":00"
                elif line.startswith('Measurement end date and time'):
                    header_data['RESULT_TIME_END'] = line.split(': ')[1].strip() + ":00"

            header_data['GRANULARITYPERIOD'] = '60'
            column_header = list()

            while len(lines) > 0:
                line = lines.pop(0).strip('\n|\r')
                if line == '':
                    column_header = list()
                    continue

                data = line.replace('?','').strip()
                if column_header == []:
                    self._command_name = command_name_list.pop(0)
                    column_header = data.upper().split('\t')
                else:
                    data = data.split('\t')
                    if len(column_header) != len(data):
                        logger.error("ERROR[GPRS]: Number of values in table {0} of sample {1} is different from number of announced columns.".format(self._command_name, file_name))
                        continue
                    document = copy.deepcopy(header_data)
                    document.update(dict(zip(column_header, data)))
                    try:
                        # Parse the date
                        data_time = FamilyObject.parseEnvelopeDataTime(header_data['RESULT_TIME_START'])
                    except ValueError as e:
                        logger.error(
                            "Could not build mediationEnvelope due to {0}: ".format(
                                e), __file__)
                        continue
                    yield {"dataTime": data_time, "granularitySec": "60", "data": document}

        except IOError:
            logger.error("ERROR[GPRS]: Could not open sample file {0} in read mode.".format(os.path.basename(file_path)))
