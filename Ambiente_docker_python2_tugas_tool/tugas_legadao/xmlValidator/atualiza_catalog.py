def atualizar_invcell(xml_path):
    parser = etree.XMLParser(remove_blank_text=True)
    tree = etree.parse(xml_path, parser)
    root = tree.getroot()

    for table in root.findall('.//table'):
        if table.get("tableName") in table_names:
            for column in table.findall('./column'):
                if column.get("bdcolname") == "INVCELL":
                    column.set("dbn0type", "ENRICH")

    tree.write("saida.xml", encoding="utf-8", pretty_print=True, xml_declaration=True)


